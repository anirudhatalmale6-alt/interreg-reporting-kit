class Doc:
    def __init__(self):
        self.d = Document()
        s = self.d.sections[0]
        s.left_margin = s.right_margin = Cm(1.6)
        n = self.d.styles["Normal"]
        n.font.name, n.font.size = "Calibri", Pt(10)

    def h(self, t, size=13, colour=NAVY, space=12):
        p = self.d.add_paragraph()
        p.paragraph_format.space_before = Pt(space)
        p.paragraph_format.space_after = Pt(4)
        r = p.add_run(clean(t))
        r.bold, r.font.size, r.font.color.rgb = True, Pt(size), colour

    def p(self, t, size=10, colour=None, italic=False, bold=False):
        par = self.d.add_paragraph()
        par.paragraph_format.space_after = Pt(4)
        r = par.add_run(clean(t))
        r.font.size, r.italic, r.bold = Pt(size), italic, bold
        if colour:
            r.font.color.rgb = colour

    def table(self, head, rows, widths=None):
        t = self.d.add_table(rows=1, cols=len(head))
        t.style = "Table Grid"
        for i, x in enumerate(head):
            c = t.rows[0].cells[i]
            c.text = ""
            r = c.paragraphs[0].add_run(clean(x))
            r.bold, r.font.size, r.font.color.rgb = True, Pt(8.5), NAVY
        for row in rows:
            cells = t.add_row().cells
            for i, v in enumerate(row):
                cells[i].text = ""
                r = cells[i].paragraphs[0].add_run(clean(v))
                r.font.size = Pt(8.5)
                if str(row[0]).startswith("TOTAL"):
                    r.bold = True
                if "[" in str(v) and "]" in str(v):
                    r.font.color.rgb = RED
        if widths:
            for row in t.rows:
                for i, w in enumerate(widths):
                    row.cells[i].width = Cm(w)
        return t

    def page(self):
        self.d.add_paragraph().add_run().add_break(WD_BREAK.PAGE)


# ------------------------------------------------------------------- checks
def check(wp_budget):
    """Everything that must be true before this is pasted into a submission."""
    fails = []

    wp_titles = {w[0]: w[1] for w in WPS}
    wp_months = {w[0]: w[4] for w in WPS}
    wp_lead = {w[0]: w[3] for w in WPS}

    # 1. Only technical work packages carry outputs.
    used = sorted({o[0] for o in OUTPUTS})
    if used != sorted(TECHNICAL):
        fails.append(f"outputs are attached to {used}, expected "
                     f"{sorted(TECHNICAL)} - the form gives WP1 and WP2 no "
                     f"output rows at all")

    # 2. Output indices contiguous from 1 within each work package.
    for wp in TECHNICAL:
        idx = [o[1] for o in OUTPUTS if o[0] == wp]
        if idx != list(range(1, len(idx) + 1)):
            fails.append(f"{wp} output indices are {idx}, must be 1..n")

    # 3. Shares sum to 1 and output budgets sum to the WP budget, to the cent.
    for wp in TECHNICAL:
        rows = [o for o in OUTPUTS if o[0] == wp]
        share = sum(o[6] for o in rows)
        if abs(share - 1.0) > 1e-9:
            fails.append(f"{wp} output shares sum to {share}, not 1.0")
        got = sum(round(wp_budget[wp] * o[6], 2) for o in rows)
        if abs(got - wp_budget[wp]) > 0.02:
            fails.append(f"{wp} output budgets sum to {got:.2f} but the work "
                         f"package holds {wp_budget[wp]:.2f}")

    # 4. Technical WP budgets plus mandatory WP budgets equal total direct.
    tot = sum(wp_budget.values())
    direct = sum(DIRECT.values())
    if abs(tot - direct) > 0.02:
        fails.append(f"work package budgets sum to {tot:.2f}, total direct "
                     f"cost is {direct:.2f}")

    # 5. Every activity sits inside its work package's own month window, and
    #    the output is not delivered before its last activity finishes.
    for wp, oi, title, tv, unit, fin, share, desc, acts in OUTPUTS:
        lo, hi = (int(x) for x in re.findall(r"M(\d+)", wp_months[wp]))
        for ai, (atitle, m0, m1, lead, adesc) in enumerate(acts, 1):
            if not (m0 <= m1):
                fails.append(f"A{wp[2]}.{oi}.{ai} runs M{m0}-M{m1}")
            if m0 < lo or m1 > hi:
                fails.append(f"A{wp[2]}.{oi}.{ai} runs M{m0}-M{m1}, outside "
                             f"{wp} which runs {wp_months[wp]}")
            if lead not in P:
                fails.append(f"A{wp[2]}.{oi}.{ai} is led by {lead!r}, "
                             f"not a partner")
        last = max(a[2] for a in acts)
        if fin < last:
            fails.append(f"Output{wp[2]}.{oi} is delivered M{fin} but its "
                         f"activities run to M{last}")
        if fin > MONTHS:
            fails.append(f"Output{wp[2]}.{oi} delivers M{fin}, past M{MONTHS}")
        if not isinstance(tv, int) or tv <= 0:
            fails.append(f"Output{wp[2]}.{oi} target value is {tv!r}")
        if not unit or unit[0].isupper():
            fails.append(f"Output{wp[2]}.{oi} unit {unit!r} reads like a "
                         f"sentence, the form wants a unit")

    # 6. Every partner leads at least one activity. A partner that leads
    #    nothing is a partner an evaluator will ask about, and a partner who
    #    will not defend the proposal.
    leads = {a[3] for o in OUTPUTS for a in o[8]} | set(
        wp_lead[wp] for wp in wp_lead)
    idle = sorted(set(P) - leads)
    if idle:
        fails.append(f"these partners lead nothing: {idle}")

    # 7. The mandatory MMM identification must be an IF-coded output. An
    #    NX-coded one would be a NEXT MED output and would not satisfy the
    #    requirement - FAQ 5.11.
    if not any(MANDATORY_MMM_PREFIX in c for c, _ in MMM_MANDATORY):
        fails.append("the mandatory MMM identification contains no "
                     f"{MANDATORY_MMM_PREFIX} output - an NX code does not "
                     "satisfy 'different from Interreg NEXT MED'")
    for code, _ in MMM_MANDATORY:
        if "MMM_NX" in code:
            fails.append(f"{code[:24]} is in the MANDATORY block but is "
                         f"NX-coded")

    # 8. Nothing invented where a programme document is the source.
    for code, body in MMM_MANDATORY + MMM_OTHER:
        if re.search(r"\b(RCO|RCR)\s?\d", body):
            fails.append(f"{code[:24]} cites an indicator code - those come "
                         f"from the Performance Framework paper, which we do "
                         f"not have")

    # 9. RAS must not appear anywhere in a partner-facing AMMOS document.
    blob = " ".join(
        [t for o in OUTPUTS for t in (o[2], o[7])]
        + [a[4] for o in OUTPUTS for a in o[8]]
        + [b for _, b in MMM_MANDATORY + MMM_OTHER])
    for forbidden in (r"\bRAS\b", r"Regione Autonoma", r"Hakanson"):
        if re.search(forbidden, blob):
            fails.append(f"the text contains {forbidden!r}, which must not "
                         f"appear in any partner-facing AMMOS document")

    assert not fails, "NOT SHIPPING:\n  - " + "\n  - ".join(fails)
    return True


