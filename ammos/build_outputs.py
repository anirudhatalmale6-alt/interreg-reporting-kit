"""The OUTPUTS layer - the piece the form needs and our work package document
never had.

    python3 build_outputs.py

WHY THIS EXISTS

The exported application form numbers everything three levels deep:

    WORK PACKAGE  ->  OUTPUT  ->  ACTIVITY        Activity {WP}.{O}.{A}

and every OUTPUT carries four things our document did not define:

    {WPX_O_Title}  {WPX_O_TargetValue} {WPX_O_TargetUnit}
    {WPX_O_Semester}  {WPX_O_Budget}

A target value, a UNIT, a semester of delivery and a budget. Until these exist
the implementation section cannot be filled at all, and award criterion 2.4
(indicators, 4 points) is scored on exactly this table.

WHAT THE FORM TEMPLATE SETTLES THAT I HAD WRONG OR DID NOT KNOW

1.  MANDATORY WORK PACKAGES HAVE NO OUTPUTS AND NO ACTIVITIES.

    The WP1 and WP2 templates in the form (tables 54 and 55) contain the
    coordinator, the involved partners and one description box. They do NOT
    contain Output rows, Activity rows, Target groups or Target group
    involvement. Only the technical template (table 56) has those.

    So there are EIGHT outputs, not ten: two each in WP3, WP4, WP5, WP6. What
    our document called activities 1.1 to 1.3 and 2.1 to 2.3 are not numbered
    items in the submission - they are prose inside one box each. They still
    get written, they just stop being numbered.

2.  WP2's TITLE IS "Communication and dissemination", not "Communication", and
    the coordinator of both WP1 and WP2 is pre-set to "Applicant". HCMR cannot
    delegate either. Ours already matched; now it is confirmed rather than
    assumed.

3.  EACH OUTPUT HAS ITS OWN BUDGET LINE, and they must sum to the work package
    budget, which must sum to total DIRECT cost (form section 4.2). That is
    asserted below, to the cent, rather than hoped for.

4.  THE OUTPUTS OVERVIEW TABLE HAS FOUR SEMESTER COLUMNS. 24 months, four
    semesters, so a semester is six months and "semester of delivery" is
    ceil(month / 6) of the month the output is finished - not of the month its
    work starts. An output delivered in M22 is semester IV.

WHAT I HAVE NOT INVENTED

Not one RCO or RCR indicator code. Those are defined in the PERFORMANCE
FRAMEWORK METHODOLOGY PAPER, which we still do not have. Every indicator cell
below says so. Target VALUES are ours and defensible; indicator CODES must be
copied from that document.
"""
