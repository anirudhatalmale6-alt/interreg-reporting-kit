    assert abs(tot_elig - TOTAL_TARGET) < 0.5, \
        f"the pre-fill does not land on the agreed {TOTAL_TARGET:,} target: " \
        f"{tot_elig:,.2f}"
    # every earmark must fit inside the CC6 line it is charged to. THIS CHECK
    # matters more after a cut than before one: HCMR's CC6 came down from
